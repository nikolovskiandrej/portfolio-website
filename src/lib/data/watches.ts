/* ── selectors ─────────────────────────────────────────── */
export function getWatch(slug: string) {
  return watches.find((w) => w.slug === slug);
}
export function getWatchesByCollection(collection: string) {
  return watches.filter((w) => w.collection === collection);
}
export function getWatchesByGender(gender: Watch["gender"]) {
  return watches.filter((w) => w.gender === gender);
}
export function getWatchesByStrap(strapType: Watch["strapType"]) {
  return watches.filter((w) => w.strapType === strapType);
}
export const featuredWatches = watches.filter((w) => w.featured);
export const newArrivals = watches.filter((w) => w.isNew);
export const limitedWatches = watches.filter((w) => w.limited);

export function relatedWatches(slug: string, limit = 4) {
  const current = getWatch(slug);
  if (!current) return watches.slice(0, limit);
  return watches
    .filter((w) => w.slug !== slug)
    .sort((a, b) => {
      const aScore = (a.collection === current.collection ? 2 : 0) + (a.gender === current.gender ? 1 : 0);
      const bScore = (b.collection === current.collection ? 2 : 0) + (b.gender === current.gender ? 1 : 0);
      return bScore - aScore;
    })
    .slice(0, limit);
}

export const priceRange = {
  min: Math.min(...watches.map((w) => w.price)),
  max: Math.max(...watches.map((w) => w.price)),
};
